/**
 * build-map.js
 * Converts the Natural Earth 1:50m Admin-0 countries GeoJSON (v5.1.2, public domain)
 * into a compact JavaScript file (assets/map/countries.js) that the game can load
 * from file:// without a web server.
 *
 * Kept properties: ADM0_A3 code, English name, label point, continent, subregion.
 * Coordinates are rounded to 3 decimal places (~110 m), which is well within the
 * generalisation of 1:50m source data.
 *
 * Usage:  node tools/build-map.js
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'ne_50m_admin_0_countries.v5.1.2.geojson');
const OUT = path.join(__dirname, '..', 'assets', 'map', 'countries.js');

const src = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const round = (n) => Math.round(n * 1000) / 1000;
const roundRing = (ring) => {
  const out = [];
  let prev = null;
  for (const [x, y] of ring) {
    const p = [round(x), round(y)];
    if (!prev || prev[0] !== p[0] || prev[1] !== p[1]) out.push(p);
    prev = p;
  }
  return out;
};

// Display-name overrides: current official short names in English (UN-style usage).
// The original Natural Earth name is retained in `neName`.
const NAME_OVERRIDES = {
  TLS: 'Timor-Leste', CIV: "Côte d'Ivoire", CHN: 'China', CZE: 'Czechia', TUR: 'Türkiye',
  CPV: 'Cabo Verde', USA: 'United States', BHS: 'Bahamas', GMB: 'Gambia',
  FSM: 'Micronesia (Federated States of)', CYN: 'Northern Cyprus', KAS: 'Siachen Glacier',
};

const features = src.features.map((f) => {
  const p = f.properties;
  const g = f.geometry;
  const geometry = g.type === 'Polygon'
    ? { type: 'Polygon', coordinates: g.coordinates.map(roundRing) }
    : { type: 'MultiPolygon', coordinates: g.coordinates.map((poly) => poly.map(roundRing)) };
  return {
    type: 'Feature',
    properties: {
      code: p.ADM0_A3,
      name: NAME_OVERRIDES[p.ADM0_A3] || p.NAME_EN || p.NAME || p.ADMIN,
      neName: p.NAME_EN || p.NAME || p.ADMIN,
      labelLat: round(p.LABEL_Y),
      labelLng: round(p.LABEL_X),
      continent: p.CONTINENT,
      subregion: p.SUBREGION,
      sovereign: p.SOVEREIGNT,
    },
    geometry,
  };
});

const header = `/* Generated by tools/build-map.js — do not edit by hand.
 * Source: Natural Earth 1:50m Cultural Vectors, Admin 0 – Countries, version 5.1.2
 * https://www.naturalearthdata.com/  (public domain)
 * Boundaries reflect Natural Earth's de facto editorial policy; other legal or political
 * perspectives may represent some borders and territories differently. */\n`;
fs.writeFileSync(OUT, header + 'window.WORLD_GEOJSON = ' + JSON.stringify({ type: 'FeatureCollection', features }) + ';\n');
console.log(`Wrote ${features.length} features to ${OUT} (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
