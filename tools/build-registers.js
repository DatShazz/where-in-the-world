const GEO = ctx.window.WORLD_GEOJSON;
const DATA = ctx.window.WITW_DATA;

function pointInRing(lng, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]; const [xj, yj] = ring[j];
    if ((yi > lat) !== (yj > lat) && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function pointInPolygon(lng, lat, poly) {
  if (!pointInRing(lng, lat, poly[0])) return false;
  for (let k = 1; k < poly.length; k++) if (pointInRing(lng, lat, poly[k])) return false;
  return true;
}
function countryAt(lat, lng) {
  for (const f of GEO.features) {
    const g = f.geometry;
    const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
    if (polys.some((p) => pointInPolygon(lng, lat, p))) return f.properties.code;
  }
  return null;
}
const codes = new Set(GEO.features.map((f) => f.properties.code));

const errors = [];
const warnings = [];
const all = [...DATA.MAIN, ...DATA.TIEBREAKERS];
const seen = new Set();
for (const q of all) {
  if (seen.has(q.id)) errors.push(`${q.id}: duplicate id`);
  seen.add(q.id);
  for (const k of ['title', 'answerName', 'category', 'difficulty', 'clueText', 'correctCountry', 'answerExplanation', 'culturalSignificance', 'surprisingFact']) {
    if (!q[k]) errors.push(`${q.id}: missing ${k}`);
  }
  if (!DATA.CATEGORIES.includes(q.category)) errors.push(`${q.id}: unknown category ${q.category}`);
  if (!DATA.REGIONS.includes(q.region)) errors.push(`${q.id}: unknown region ${q.region}`);
  if (!q.factualSources.length) errors.push(`${q.id}: no factual sources`);
  for (const c of q.acceptedCountryCodes) if (!codes.has(c)) errors.push(`${q.id}: country code ${c} not in map data`);
  const at = countryAt(q.correctLatitude, q.correctLongitude);
  if (!at) warnings.push(`${q.id}: answer marker is offshore (${q.correctLatitude}, ${q.correctLongitude}) — sea tolerance applies`);
  else if (!q.acceptedCountryCodes.includes(at)) errors.push(`${q.id}: answer marker falls in ${at}, not in ${q.acceptedCountryCodes.join('/')}`);
  if (q.clueType === 'image') {
    if (!q.imagePath) warnings.push(`${q.id}: image question without a verified image (fallback card will show)`);
    else if (!fs.existsSync(rel(q.imagePath))) errors.push(`${q.id}: image file missing ${q.imagePath}`);
    if (!q.imageAltText) errors.push(`${q.id}: image without alt text`);
  }
  if (q.clueType === 'audio' && !q.audioDescription) errors.push(`${q.id}: audio clue without text description`);
}

