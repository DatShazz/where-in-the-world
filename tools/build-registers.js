/* ---------- Optional URL check ---------- */
(async () => {
  if (process.argv.includes('--check-urls')) {
    const urls = [...new Set(all.flatMap((q) => q.factualSources.map((s) => s.url)))];
    let bad = 0;
    for (const u of urls) {
      try {
        const r = await fetch(u, { method: 'GET', redirect: 'follow', headers: { 'User-Agent': 'WhereInTheWorldGame/1.0 (source checker)' } });
        if (!r.ok) { bad++; console.log('URL', r.status, u); }
      } catch (e) { bad++; console.log('URL ERR', u, e.message); }
      await new Promise((ok) => setTimeout(ok, 150));
    }
    console.log(`Checked ${urls.length} source URLs, ${bad} problems.`);
  }
  console.log(errors.length ? `\n${errors.length} ERROR(S)` : '\nValidation passed.');
  process.exitCode = errors.length ? 1 : 0;
})();
